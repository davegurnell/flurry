import { useDeferredValue, useMemo } from "react";
import { buildSVG } from "../engine/svg.js";

export function Board({ doc, bg }) {
  // Keep slider drags responsive on big designs: render the preview at lower priority.
  const deferred = useDeferredValue(doc);
  const { svg, count } = useMemo(() => buildSVG(deferred, { preview: true }), [deferred]);
  const visible = deferred.layers.filter((l) => l.visible).length;

  return (
    <main className="stage">
      <div className="canvas-area">
        {/* The SVG is generated by our own engine; layer names are escaped there. */}
        <div className="board" data-bg={bg} role="img" aria-label={`Preview of ${doc.name}`} dangerouslySetInnerHTML={{ __html: svg }} />
      </div>
      <div className="stage-bar">
        <span>Transparent SVG · 1000 × 1000 · scales to any print size</span>
        <span className="stats">{visible} layers · {count.toLocaleString()} shapes</span>
      </div>
    </main>
  );
}
